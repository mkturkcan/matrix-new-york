"""Scripted driving "routes" expressed as Matrix-Game-3 action sequences.

Matrix-Game-3 is conditioned per frame on
  * keyboard: 6-dim multi-hot  [W, S, A, D, -, -]  (W = forward, A/D = strafe)
  * mouse:    2-dim            [pitch, yaw]         (15 deg per unit per frame, deadzone 0.02)

We drive like a car: W is the throttle, the yaw channel is the steering wheel,
and short A/D strafes while holding W read as lane changes.
"""
import numpy as np
import torch

FPS = 17                 # Matrix-Game-3 output frame rate
STEER = 0.06             # yaw command for normal steering (0.9 deg / frame)
CURVE = 0.03             # yaw command for gentle highway curves
TURN = 0.10              # yaw command for a 90-degree intersection turn (~60 frames)


def num_frames_for(num_iterations: int) -> int:
    """Total frames generated by Matrix-Game-3 for a given number of iterations."""
    return 57 + (num_iterations - 1) * 40


# A route is a list of (seconds, keys, yaw). keys is a string over "wsad".
ROUTES = {
    # Straight cruise, e.g. down an avenue.
    "cruise": [
        (60.0, "w", 0.0),
    ],
    # Highway: cruise, gentle curves and two lane changes.
    "highway": [
        (4.0, "w", 0.0),
        (2.5, "w", CURVE),
        (3.0, "w", 0.0),
        (1.0, "wa", 0.0),     # lane change left
        (4.0, "w", 0.0),
        (2.5, "w", -CURVE),
        (3.0, "w", 0.0),
        (1.0, "wd", 0.0),     # lane change right
        (60.0, "w", 0.0),
    ],
    # Downtown: stay in the avenue, change lanes and nudge the wheel.
    # (Full 90-degree turns mid-block steer the camera into storefronts.)
    "downtown": [
        (5.0, "w", 0.0),
        (1.2, "wd", 0.0),     # lane change right
        (4.0, "w", 0.0),
        (2.0, "w", -CURVE),
        (2.0, "w", CURVE),
        (1.2, "wa", 0.0),     # lane change left
        (60.0, "w", 0.0),
    ],
    # Intersection turn: only use where the first frame is AT an intersection.
    "turn_right": [
        (2.0, "w", 0.0),
        (3.5, "w", TURN),
        (60.0, "w", 0.0),
    ],
    # Weaving through traffic.
    "weave": [
        (2.0, "w", 0.0),
        (1.0, "wa", -0.03),
        (2.0, "w", 0.0),
        (1.0, "wd", 0.03),
        (2.0, "w", 0.0),
        (1.0, "wd", 0.03),
        (2.0, "w", 0.0),
        (1.0, "wa", -0.03),
        (60.0, "w", 0.0),
    ],
    # Look around while rolling slowly (sightseeing).
    "sightseeing": [
        (3.0, "w", 0.0),
        (3.0, "w", -STEER),
        (3.0, "w", STEER),
        (3.0, "w", STEER),
        (3.0, "w", -STEER),
        (60.0, "w", 0.0),
    ],
}

KEY_COL = {"w": 0, "s": 1, "a": 2, "d": 3}


def build_actions(route, num_frames: int):
    """Expand a route (name or list of segments) into per-frame action tensors."""
    if isinstance(route, str):
        route = ROUTES[route]
    keyboard = torch.zeros((num_frames, 6))
    mouse = torch.zeros((num_frames, 2))
    t = 0
    for seconds, keys, yaw in route:
        n = max(1, int(round(seconds * FPS)))
        end = min(num_frames, t + n)
        for k in keys:
            keyboard[t:end, KEY_COL[k]] = 1
        mouse[t:end, 1] = yaw
        t = end
        if t >= num_frames:
            break
    if t < num_frames:  # pad with cruising
        keyboard[t:, 0] = 1
    return {"keyboard_condition": keyboard, "mouse_condition": mouse}


def speed_profile(keyboard: np.ndarray, top_speed: float) -> np.ndarray:
    """Fake speedometer for the HUD: accelerate while W is held, coast otherwise."""
    v, out = 0.0, []
    for k in keyboard:
        target = top_speed if k[0] > 0.5 else (0.0 if k[1] > 0.5 else v * 0.98)
        v += (target - v) * 0.06
        out.append(v)
    return np.array(out)
